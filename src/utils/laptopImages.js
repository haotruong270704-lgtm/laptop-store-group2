export function getLaptopImage(laptop) {
  if (!laptop) return '/no-image.svg';
  // Nếu có ảnh hợp lệ và không phải placehold.co
  if (laptop.image && !laptop.image.includes('placehold.co')) {
    return laptop.image;
  }
  const id = Number(laptop.id);
  const found = LAPTOP_IMAGE_MAP[id];
  if (found?.main) return found.main;

  // Fallback theo tên hoặc thương hiệu
  const name = String(laptop.name || '').toLowerCase();
  if (name.includes('macbook')) return '/images/laptops/macbook-pro-14.jpg';
  if (name.includes('dell') || name.includes('xps')) return '/images/laptops/dell-xps-13.jpg';
  if (name.includes('gaming') || name.includes('rog') || name.includes('nitro') || name.includes('legion')) {
    return 'https://images.unsplash.com/photo-1603302576837-37561b2e2302?auto=format&fit=crop&w=800&q=80';
  }
  if (name.includes('thinkpad')) {
    return 'https://images.unsplash.com/photo-1588702547919-26089e690ecc?auto=format&fit=crop&w=800&q=80';
  }
  return '/images/laptops/macbook-pro-14.jpg';
}

export function getLaptopGallery(laptop) {
  if (!laptop) return [];
  const id = Number(laptop.id);
  const found = LAPTOP_IMAGE_MAP[id];
  if (found?.gallery?.length) {
    return found.gallery;
  }
  const main = getLaptopImage(laptop);
  return [main];
}
